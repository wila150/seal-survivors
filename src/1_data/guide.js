// data：{ JOBS, SKILLS（skills.json）, TALENTS（talents.json）, STAGES, NPCS }
export function buildGuide({ JOBS, SKILLS, TALENTS, STAGES, NPCS }) {
  const out = STATIC.map(([cat, title, body, kind]) => ({ cat, title, body, kind }));
  for (const [job, J] of Object.entries(JOBS)) {
    const S = SKILLS.jobs[job], nm = k => SKILLS.skills[k]?.name || k, br = TALENTS?.jobs[job]?.branches || [];
    const fu = SKILLS.fusions.find(f => S?.pool.includes(f.a));
    out.push({ cat: '職業', title: job, body: `${J.desc || ''}<br>HP ${J.hp}・移速 ${J.speed}・護甲 ${J.armor}${S ? `<br>普攻：${nm(S.basic)}<br>技能：${S.pool.map(nm).join('、')}${fu ? `<br>超武：${nm(fu.a)}＋${nm(fu.b)} → ${nm(fu.into)}` : ''}` : ''}
      ${br.length ? `<br>二轉：${br.map(b => `${b.name}（${b.skills.map(nm).join('、')}）→ 三轉 ${b.third}`).join('；')}` : ''}` });
  }
  STAGES.forEach((s, i) => out.push({ cat: '地圖與首領', title: s.name, body: `建議等級 ${s.lv}・獎勵 ×${s.reward}${i ? `・通關「${STAGES[i - 1].name}」後解鎖` : '・一開始就能去'}
    ${s.zones ? `<br>區域：${s.zones.map(z => z.name).join('、')}（站在哪一區就出哪一區的怪）` : ''}
    <br>首領：${s.bosses.map(([t, n, k]) => `${String(t / 60 | 0)}:${String(t % 60).padStart(2, '0')} ${n}${k === 'mvp' ? '（MVP）' : ''}`).join('、')}` }));
  const NPC_TXT = { captain: '選地圖出征', job: '二轉', shop: '販賣、礦石、限量裝備', smith: '精煉', storage: '帳號共用倉庫', rank: '排行榜', library: '新手指南、怪物圖鑑',
    mount: '租坐騎', pet: '寵物（買蛋、出戰、餵食、改名）', auction: '拍賣所', stylist: '髮型、髮色、服裝配色（免費）', ident: '技能屬性鑑定', zaro: '分解裝備、閃亮粉末換結晶', mail: '信箱、系統獎勵', rebirth: '轉生' };
  for (const n of NPCS) out.push({ cat: '主城人物', title: n.name, body: NPC_TXT[n.id] || '' });
  return out;
}
